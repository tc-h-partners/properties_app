@Injectable()
export class BenchmarksService {
  constructor(private readonly prisma: PrismaService) {}

  async getSystemSettings() {
    const existing = await this.prisma.marketBenchmark.findFirst({
      where: {
        state: 'SYS_CFG',
        suburb: GOVERNANCE_SUBURB_KEY,
      },
    });

    if (existing && existing.sourceNotes) {
      try {
        const parsed = JSON.parse(existing.sourceNotes);
        if (!parsed.advisors || !Array.isArray(parsed.advisors) || parsed.advisors.length === 0) {
          parsed.advisors = DEFAULT_SYSTEM_SETTINGS.advisors;
        }
        if (!parsed.dropdowns || typeof parsed.dropdowns !== 'object') {
          parsed.dropdowns = DEFAULT_SYSTEM_SETTINGS.dropdowns;
        }
        return parsed;
      } catch {
        // Fallback to default if malformed
      }
    }

    await this.saveSystemSettings(DEFAULT_SYSTEM_SETTINGS);
    return DEFAULT_SYSTEM_SETTINGS;
  }

  async saveSystemSettings(payload: Record<string, any>) {
    const existing = await this.prisma.marketBenchmark.findFirst({
      where: {
        state: 'SYS_CFG',
        suburb: GOVERNANCE_SUBURB_KEY,
      },
    });

    let existingParsed: Record<string, any> = {};
    if (existing && existing.sourceNotes) {
      try {
        existingParsed = JSON.parse(existing.sourceNotes);
      } catch {}
    }

    const merged = {
      benchmarks: Array.isArray(payload.benchmarks)
        ? payload.benchmarks
        : existingParsed.benchmarks || DEFAULT_SYSTEM_SETTINGS.benchmarks,
      picfoMetrics: Array.isArray(payload.picfoMetrics)
        ? payload.picfoMetrics
        : existingParsed.picfoMetrics || DEFAULT_SYSTEM_SETTINGS.picfoMetrics,
      advisors: Array.isArray(payload.advisors)
        ? payload.advisors
        : existingParsed.advisors || DEFAULT_SYSTEM_SETTINGS.advisors,
      dropdowns: payload.dropdowns || existingParsed.dropdowns || DEFAULT_SYSTEM_SETTINGS.dropdowns,
    };

    if (existing) {
      await this.prisma.marketBenchmark.update({
        where: { id: existing.id },
        data: {
          sourceNotes: JSON.stringify(merged),
        },
      });
    } else {
      await this.prisma.marketBenchmark.create({
        data: {
          effectiveDate: new Date('2026-06-30T00:00:00.000Z'),
          state: 'SYS_CFG',
          suburb: GOVERNANCE_SUBURB_KEY,
          sourceNotes: JSON.stringify(merged),
        },
      });
    }

    return merged;
  }

  async findAll() {
    return this.prisma.marketBenchmark.findMany({
      where: {
        NOT: {
          state: 'SYS_CFG',
        },
      },
      orderBy: [{ effectiveDate: 'desc' }, { state: 'asc' }],
    });
  }

  async findOne(id: string) {
    const item = await this.prisma.marketBenchmark.findUnique({ where: { id } });
    if (!item) throw new NotFoundException(`Market benchmark ${id} not found`);
    return item;
  }

  async create(dto: CreateBenchmarkDto) {
    return this.prisma.marketBenchmark.create({
      data: {
        effectiveDate: new Date(dto.effectiveDate),
        state: dto.state?.toUpperCase() || null,
        suburb: dto.suburb || null,
        propertyCategory: dto.propertyCategory || null,
        benchmarkInterestRate: dto.benchmarkInterestRate,
        benchmarkGrossYield: dto.benchmarkGrossYield,
        benchmarkWeeklyRent: dto.benchmarkWeeklyRent,
        benchmarkRentalGrowth: dto.benchmarkRentalGrowth,
        benchmarkCapitalGrowth: dto.benchmarkCapitalGrowth,
        asxIndexValue: dto.asxIndexValue,
        sourceNotes: dto.sourceNotes,
      },
    });
  }

  async update(id: string, dto: UpdateBenchmarkDto) {
    await this.findOne(id);
    return this.prisma.marketBenchmark.update({
      where: { id },
      data: {
        effectiveDate: dto.effectiveDate ? new Date(dto.effectiveDate) : undefined,
        state: dto.state !== undefined ? dto.state?.toUpperCase() || null : undefined,
        suburb: dto.suburb !== undefined ? dto.suburb || null : undefined,
        propertyCategory: dto.propertyCategory !== undefined ? dto.propertyCategory || null : undefined,
        benchmarkInterestRate: dto.benchmarkInterestRate,
        benchmarkGrossYield: dto.benchmarkGrossYield,
        benchmarkWeeklyRent: dto.benchmarkWeeklyRent,
        benchmarkRentalGrowth: dto.benchmarkRentalGrowth,
        benchmarkCapitalGrowth: dto.benchmarkCapitalGrowth,
        asxIndexValue: dto.asxIndexValue,
        sourceNotes: dto.sourceNotes,
      },
    });
  }

  async remove(id: string) {
    await this.findOne(id);
    return this.prisma.marketBenchmark.delete({ where: { id } });
  }
}
