function computeLatestFy(historicalValues: HistoricalValueItem[]): string {
  if (!Array.isArray(historicalValues) || historicalValues.length === 0) {
    return "";
  }
  const years: number[] = [];
  for (const hv of historicalValues) {
    const fyMatch = String(hv.fy || "").match(/\d{4}/);
    if (fyMatch) {
      years.push(Number(fyMatch[0]));
      continue;
    }
    const dateMatch = String(hv.date || "").match(/(\d{4})$/);
    if (dateMatch) {
      years.push(Number(dateMatch[1]));
    }
  }
  if (years.length === 0) {
    return historicalValues[historicalValues.length - 1]?.fy || "";
  }
  return String(Math.max(...years));
}

